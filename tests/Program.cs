// The damage meter can join mid-run, miss events, and receive fresh snapshots
// after a new cycle. Native cumulative totals must not become recent hit damage.
var nativeTotals = new GameDamageTotals();
var loopLedger = new BattleLedger();
loopLedger.Identify(1, "one", "FFFFFF");
loopLedger.Record(1, 4, 100, 1199, false);
loopLedger.StartBoss(1198);
loopLedger.Record(1, 4, 20, 1200, true);
Assert(nativeTotals.Update(1, 437108300, new Dictionary<int, double> { [4] = 437108300 }), "Accept cumulative game damage");
var beforeLoop = loopLedger.Snapshot(1200, 10);
nativeTotals.Apply(beforeLoop);
Equal(437108300, beforeLoop.Players.Single().Damage, "Player damage comes from the game rather than observed hits");
Equal(437108300, beforeLoop.Players.Single().Spells.Single().Damage, "Spell damage matches native statistics");
Equal(12, beforeLoop.Players.Single().Dps, "Importing cumulative damage does not create a rolling DPS spike");
Equal(20, beforeLoop.Players.Single().BossDamage, "Native run damage does not alter boss damage");
Equal(10, beforeLoop.Players.Single().BossDps, "Native run damage does not alter boss DPS");
loopLedger.FinishBoss(1200);
loopLedger.Record(1, 4, 80, 1201, false);
Assert(nativeTotals.Update(1, 437108380, new Dictionary<int, double> { [4] = 437108380 }), "Next cycle updates cumulative game damage");
var afterLoop = loopLedger.Snapshot(1201, 10);
nativeTotals.Apply(afterLoop);
Equal(437108380, afterLoop.Players.Single().Damage, "Next loop retains all previous damage");
Equal(20, afterLoop.Players.Single().Dps, "Rolling DPS spans a cycle boundary without resetting");
Equal(437108380, afterLoop.Players.Single().Spells.Single().Damage, "Spell totals remain cumulative after a loop");
var later = loopLedger.Snapshot(1220, 10);
nativeTotals.Apply(later);
Equal(0, later.Players.Single().Dps, "Rolling window still expires normally");
Equal(437108380, later.Players.Single().Damage, "Game totals survive an expired rolling window");
Equal(10, later.Players.Single().BossDps, "Finished boss DPS remains frozen across loops");
Assert(nativeTotals.Update(2, 624549000, new Dictionary<int, double> { [5] = 187440700, [6] = 437108300 }), "Native stats can recover a player with no observed hits");
nativeTotals.Apply(later);
Assert(later.Players[0].Id == 2, "Players are sorted by native cumulative damage");
Assert(later.Players[0].Spells[0].Spell == 6, "Spells are sorted by native cumulative damage");
Equal(0, later.Players[0].Spells[0].Dps, "A recovered spell has no invented recent damage");
Equal(624549000, later.Players[0].Spells.Sum(x => x.Damage), "Recovered spell totals are complete");
Assert(!nativeTotals.Update(1, double.NaN, new Dictionary<int, double>()), "Reject invalid native player damage");
Assert(!nativeTotals.Update(1, 1, new Dictionary<int, double> { [4] = double.PositiveInfinity }), "Reject invalid native spell damage atomically");
Assert(!nativeTotals.Update(1, -1, new Dictionary<int, double>()), "Reject negative native damage");
