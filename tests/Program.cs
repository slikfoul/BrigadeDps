using BrigadeDps;
using System.Text.Json;

int checks = 0;
void Assert(bool condition, string label) { if (!condition) throw new Exception(label); checks++; }
void Equal(double expected, double actual, string label) => Assert(Math.Abs(expected - actual) < .000001, $"{label}: {actual} != {expected}");
var data = new BattleLedger();
data.Identify(1, "one", "FF0000"); data.Identify(2, "two", "00FF00"); data.Identify(3, "idle", "FFFFFF");
data.Record(1, 4, 120, 1, false);
data.Record(2, 5, 80, 2, false);
var state = data.Snapshot(10, 10);
Assert(state.Players.Count == 3, "Zero-damage teammates are included");
Equal(12, state.Players.Single(p => p.Id == 1).Dps, "10-second DPS");
Equal(0, data.Snapshot(11, 10).Players.Single(p => p.Id == 1).Dps, "Expired hit leaves window");
Equal(120, data.Snapshot(11, 10).Players.Single(p => p.Id == 1).Damage, "Total survives window expiry");
data.StartBoss(20);
data.Record(1, 4, 300, 21, true); data.Record(2, 5, 100, 22, true);
data.Record(1, 7, 900, 23, false);
state = data.Snapshot(25, 10);
Equal(60, state.Players.Single(p => p.Id == 1).BossDps, "Boss DPS uses elapsed encounter time");
Equal(300, state.Players.Single(p => p.Id == 1).BossDamage, "Adds do not count as boss damage");
Equal(75, 100 * state.Players.Single(p => p.Id == 1).BossDamage / state.Players.Sum(p => p.BossDamage), "Boss share");
Equal(0, state.Players.Single(p => p.Id == 3).BossDamage, "Zero boss contribution visible");
data.FinishBoss(25);
state = data.Snapshot(100, 10);
Equal(60, state.Players.Single(p => p.Id == 1).BossDps, "Boss DPS freezes after defeat");
Equal(5, state.BossSeconds, "Boss duration freezes");
Assert(!state.BossActive && state.HasBoss, "Finished boss remains available");
Equal(25, state.BossEndedAt.Value, "Boss death timestamp is retained");
var lifetime = new BossDisplayLifetime();
lifetime.Observe(data.Snapshot(25, 10), 1000);
Assert(lifetime.Show(1009.99, 10), "Boss totals remain visible for ten seconds after death");
Assert(!lifetime.Show(1010, 10), "Boss totals hide at the configured timeout");
lifetime.Observe(data.Snapshot(25, 10), 1015);
Assert(!lifetime.Show(1015, 10), "Frozen results and repeated packets do not restart the timeout");
Assert(lifetime.Show(1015, 30), "Increasing retention uses elapsed time since the same death");
Assert(!lifetime.Show(1000, 0), "Zero retention hides defeated boss immediately");
var lateViewer = new BossDisplayLifetime();
lateViewer.Observe(data.Snapshot(100, 10), 500);
Assert(!lateViewer.Show(500, 10), "Late viewer does not redisplay an expired boss");
var delayedViewer = new BossDisplayLifetime();
delayedViewer.Observe(data.Snapshot(28, 10), 500);
Assert(delayedViewer.Show(506.9, 10) && !delayedViewer.Show(507, 10), "Received death timestamp accounts for already elapsed time");
var legacy = new MeterSnapshot { HasBoss = true, BossActive = false };
var legacyViewer = new BossDisplayLifetime(); legacyViewer.Observe(legacy, 100);
Assert(legacyViewer.Show(109, 10) && !legacyViewer.Show(110, 10), "Older hosts fall back to receipt time");
lifetime.Observe(new MeterSnapshot(), 1020);
Assert(!lifetime.Show(1020, 3600), "New run clears displayed boss lifetime");
data.StartBoss(100);
lifetime.Observe(data.Snapshot(100, 10), 1030);
Assert(lifetime.Show(9999, 0), "Active boss remains visible regardless of retention");
Assert(data.Snapshot(100, 10).BossEndedAt == null, "New boss clears death timestamp");
data.FinishBoss(101);
lifetime.Observe(data.Snapshot(101, 10), 1040);
Assert(lifetime.Show(1049, 10) && !lifetime.Show(1050, 10), "Next boss gets an independent countdown");
data.StartBoss(100);
Equal(0, data.Snapshot(100, 10).Players.Sum(p => p.BossDamage), "Next boss resets boss totals");
Equal(1500, data.Snapshot(100, 10).Players.Sum(p => p.Damage), "Next boss preserves run total");
var invalid = new DamageSeries();
invalid.Add(1, double.NaN, 0); invalid.Add(1, double.PositiveInfinity, 0); invalid.Add(1, -5, 0);
Equal(0, invalid.Total, "Ignore invalid damage");
invalid.Add(1, 100, 0); invalid.Add(61.1, 50, 0);
Equal(5, invalid.Rate(61.1, 0, 10), "Ring wrap does not retain old damage");
var roundtrip = JsonSerializer.Deserialize<MeterSnapshot>(JsonSerializer.Serialize(state));
Equal(state.Players[0].BossDamage, roundtrip.Players[0].BossDamage, "Network payload round trip");
Equal(25, roundtrip.BossEndedAt.Value, "Death timestamp survives transport");
Assert(!VisibilityPolicy.Show(true, false, false, true), "Main menu hides even with saved results");
Assert(!VisibilityPolicy.Show(true, false, false, false), "Lobby hides");
Assert(VisibilityPolicy.Show(true, true, false, true), "Active run shows");
Assert(VisibilityPolicy.Show(true, false, true, true), "Results panel shows");
Assert(!VisibilityPolicy.Show(true, false, true, false), "Results preference respected");
Assert(!VisibilityPolicy.Show(false, true, false, true), "Disable respected");
data.Clear(); Assert(data.Snapshot(0, 10).Players.Count == 0 && !data.HasBoss, "New run clears previous data");
data.Record(1, 4, 100, 1, false);
data.Record(1, 5, 200, 5, false);
data.Record(1, -30, 50, 6, false);
var perSpell = data.Snapshot(10, 10).Players.Single();
Equal(10, perSpell.Spells.Single(s => s.Spell == 4).Dps, "First spell rolling DPS");
Equal(20, perSpell.Spells.Single(s => s.Spell == 5).Dps, "Second spell has independent DPS");
Equal(perSpell.Dps, perSpell.Spells.Sum(s => s.Dps), "Spell and non-spell DPS add up to player DPS");
Equal(350, perSpell.Damage, "Hidden non-spell damage stays in player total");
Assert(!perSpell.Spells.Where(s => UiText.IsSpell(s.Spell)).Any(s => s.Spell == -30), "Non-spell rows hidden");
Equal(0, data.Snapshot(11, 10).Players.Single().Spells.Single(s => s.Spell == 4).Dps, "Spell DPS expires independently");
Equal(20, data.Snapshot(11, 10).Players.Single().Spells.Single(s => s.Spell == 5).Dps, "Other spell stays in rolling window");
data.Record(1, 4, 40, 61.1, false);
Equal(4, data.Snapshot(61.1, 10).Players.Single().Spells.Single(s => s.Spell == 4).Dps, "Per-spell ring wrap");
var payload = data.Snapshot(61.1, 10);
roundtrip = JsonSerializer.Deserialize<MeterSnapshot>(JsonSerializer.Serialize(payload));
Assert(roundtrip.Protocol == 2, "Spell DPS transport version");
Equal(4, roundtrip.Players.Single().Spells.Single(s => s.Spell == 4).Dps, "Per-spell DPS survives transport");
Assert(UiText.Translate("Готово", "en-US") == "Done", "English UI follows game locale");
Assert(UiText.Translate("Готово", "ru-RU") == "Готово", "Russian UI follows game locale");
Assert(UiText.Translate("Готово", "fr") == "Done", "Other languages use English fallback");
Assert(UiText.SpellLabel("Крылья зари", true, true) == "КЗ", "Russian initials");
Assert(UiText.SpellLabel("Wings of Dawn", true, true) == "WOD", "English initials");
Assert(UiText.SpellLabel("Titan's Hammer", true, true) == "TH", "Apostrophe stays inside word");
Assert(UiText.SpellLabel("Крылья зари", true, false) == "Крылья зари", "Full name mode");
Assert(UiText.SpellLabel("Wings of Dawn", false, true) == "", "Icon-only mode takes priority");
foreach (bool right in new[] { false, true })
foreach (bool bottom in new[] { false, true })
{
    float originalX = right ? 1590 : 30, originalY = bottom ? 960 : 20;
    var ax = WindowAnchorAxis.Capture(originalX, 300, 1920, 6, right);
    var ay = WindowAnchorAxis.Capture(originalY, 100, 1080, 6, bottom);
    Assert(ax.FarEdge == right && ay.FarEdge == bottom, "Configured direction respected independently per axis");
    Equal(right ? 1390 : 30, ax.Resolve(500, 1920, 6), "Growth preserves chosen horizontal edge");
    Equal(bottom ? 760 : 20, ay.Resolve(300, 1080, 6), "Growth preserves chosen vertical edge");
    Equal(originalX, ax.Resolve(300, 1920, 6), "Shrink restores original horizontal edge");
    Equal(originalY, ay.Resolve(100, 1080, 6), "Shrink restores original vertical edge");
}
var farAnchor = WindowAnchorAxis.Capture(1590, 300, 1920, 6, true);
Equal(860, farAnchor.Resolve(400, 1280, 6), "Resolution change keeps proportional right margin");
Equal(6, farAnchor.Resolve(1908, 1920, 6), "Oversized growth is clamped inside the opposite edge");
Equal(1590, farAnchor.Resolve(300, 1920, 6), "Clamping does not destroy saved edge margin");
var movedLeft = WindowAnchorAxis.Capture(20, 300, 1920, 6, true);
Assert(movedLeft.FarEdge, "Dragging left preserves the configured leftward growth");
Equal(20, movedLeft.Resolve(300, 1920, 6), "Changing anchor does not jump at the same size");
var movedRight = WindowAnchorAxis.Capture(1590, 300, 1920, 6, false);
Assert(!movedRight.FarEdge, "Dragging right preserves the configured rightward growth");
Equal(1590, movedRight.Resolve(300, 1920, 6), "Right-side placement remains stable with a left anchor");
Equal(1414, movedRight.Resolve(500, 1920, 6), "Manual rightward growth is still limited by the screen");
Assert(UiText.Translate("УРОН", "en-US") == "DMG", "Compact English damage header");
Assert(UiText.Translate("УВС", "ru-RU") == "УВС", "Russian damage-per-second header");
Assert(UiText.Translate("УВС", "en") == "DPS", "English damage-per-second header");
Assert(UiText.Translate("Влево", "en") == "Left" && UiText.Translate("Вверх", "en") == "Up", "Growth direction localization");
foreach (float scale in new[] { .6f, 1f, 1.8f })
foreach (bool far in new[] { false, true })
foreach (float size in new[] { 100f, 900f, 1920 - 12 * scale })
{
    float padding = 6 * scale;
    float p = new WindowAnchorAxis(far, .15f).Resolve(size, 1920, padding);
    Assert(p >= padding - .001 && p + size <= 1920 - padding + .001, "Frame stays on screen at every scale and edge");
}
Console.WriteLine($"PASS: {checks} checks (DPS, transport, RU/EN, initials, edge growth, resizing bounds)");
